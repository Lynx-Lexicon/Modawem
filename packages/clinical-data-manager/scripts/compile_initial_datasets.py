def compile_ddi_dataset(output_file: Path) -> int:
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=DDI_HEADER)
        writer.writeheader()
        for rec in DDI_RECORDS:
            row = dict(rec)
            # Ensure canonical interaction_group_id is populated consistently
            group_id = make_canonical_group_id(
                row["ingredient_a_id_system"],
                row["ingredient_a_id"],
                row["ingredient_b_id_system"],
                row["ingredient_b_id"],
            )
            row["interaction_group_id"] = group_id
            writer.writerow(row)
    return len(DDI_RECORDS)


def compile_allergy_dataset(output_file: Path) -> int:
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=ALLERGY_HEADER)
        writer.writeheader()
        for rec in ALLERGY_RECORDS:
            writer.writerow(rec)
    return len(ALLERGY_RECORDS)


def copy_file(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.exists():
        shutil.copy2(src, dst)
        print(f"  [COPY] {src.name} -> {dst}")
    else:
        print(f"  [WARN] Source file not found: {src}")


